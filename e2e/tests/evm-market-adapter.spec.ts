import { test, expect } from '@playwright/test';
import path from 'node:path';
import { localMarketChain } from '../../backend/test/helpers/evm-market-chain.cjs';
const frontend = path.resolve(__dirname, '../../frontend');
let chain: any;
test.beforeAll(async () => { chain = await localMarketChain(); });
test.afterAll(async () => { await chain?.close(); });
test('EVM dialog trades with keyboard, restores state, and handles rejected signatures at 390px', async ({ page }, testInfo) => {
    test.setTimeout(60000);
    const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
    const agreement = await chain.createAgreement();
    await chain.adapter(chain.sponsor).open({ key: agreement.key, liquidity: '5000000', maxFunding: '3500000' });
    await page.route(`${chain.url}/ui`, route => route.fulfill({ contentType: 'text/html', body: '<html><body><button id="opener">Open bet</button></body></html>' }));
    await page.goto(`${chain.url}/ui`);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.addStyleTag({ path: path.join(frontend, 'css/tokens.css') });
    await page.addStyleTag({ path: path.join(frontend, 'css/primitives.css') });
    for (const file of ['vendor/ethers-6.17.0/ethers.umd.min.js', 'js/ui/dialogs.js', 'js/ui/modal-escape.js', 'js/ui/busy-control.js', 'js/chain/evm-markets.js', 'js/chain/evm-market-dialog.js']) await page.addScriptTag({ path: path.join(frontend, file) });
    await page.evaluate(({ url, addresses, wallet, key }) => {
        const w = window as any;
        let rpcId = 0;
        w.rejectMarketSignature = false;
        const injected = { request: async ({ method, params = [] }) => {
            if (['eth_accounts', 'eth_requestAccounts'].includes(method)) return [wallet];
            if (method === 'eth_sendTransaction' && w.rejectMarketSignature) throw Object.assign(new Error('User rejected signature'), { code: 4001 });
            const response = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: ++rpcId, method, params }) });
            const result = await response.json(); if (result.error) throw Object.assign(new Error(result.error.message), result.error); return result.result;
        } };
        w.walletManager = { getState: () => ({ status: 'connected', chainId: '0x7a69', accounts: [wallet] }), getProvider: () => injected };
        const provider = new w.ethers.JsonRpcProvider(url, 31337, { staticNetwork: true, cacheTimeout: -1 }); provider.pollingInterval = 20;
        w.ChainDataLoader = { getProviderForChain: async () => provider };
        w.EvmAdapter = { ensureEthers: async () => w.ethers, contractAddresses: async () => addresses, walletChainId: () => '31337', explorerUrl: () => null };
        w.EvmAgreementBridge = { onchainRef: a => a.onchain };
        document.getElementById('opener')!.onclick = () => w.EvmMarketDialog.open({ title: 'Local agreement', onchain: { chainId: '31337', account: key } });
    }, { url: chain.url, addresses: chain.addresses, wallet: await chain.trader.getAddress(), key: agreement.key });
    await page.getByRole('button', { name: 'Open bet', exact: true }).press('Enter');
    const dialog = page.getByRole('dialog');
    await expect(dialog.getByText(/50.0% YES/)).toBeVisible();
    await dialog.getByLabel('Shares', { exact: true }).fill('0.1');
    await dialog.getByRole('button', { name: 'Get quote', exact: true }).press('Enter');
    await expect(dialog.getByRole('button', { name: 'Confirm trade', exact: true })).toBeEnabled();
    await dialog.getByRole('button', { name: 'Confirm trade', exact: true }).press('Enter');
    await expect(dialog.getByRole('status')).toHaveText('Confirmed', { timeout: 20000 });
    await expect(dialog.getByText(/Shares: 0.1 YES/)).toBeVisible();
    expect((await chain.adapter(chain.trader).read(agreement.key)).positions.yes).toBe(100000n);
    await page.keyboard.press('Escape');
    await expect(page.getByRole('button', { name: 'Open bet', exact: true })).toBeFocused();
    await page.getByRole('button', { name: 'Open bet', exact: true }).press('Enter');
    await expect(page.getByText(/Shares: 0.1 YES/)).toBeVisible();
    await dialog.getByLabel('Trade', { exact: true }).selectOption('sell');
    await dialog.getByLabel('Shares', { exact: true }).fill('0.05');
    await dialog.getByRole('button', { name: 'Get quote', exact: true }).press('Enter');
    await expect(dialog.getByRole('button', { name: 'Confirm trade', exact: true })).toBeEnabled();
    await page.evaluate(() => { (window as any).rejectMarketSignature = true; });
    await dialog.getByRole('button', { name: 'Confirm trade', exact: true }).press('Enter');
    await expect(dialog.getByRole('status')).toContainText(/rejected|denied/i);
    await expect(dialog.locator('[aria-busy="true"]')).toHaveCount(0);
    await expect(dialog.getByRole('button', { name: 'Get quote', exact: true })).toBeEnabled();
    expect((await chain.adapter(chain.trader).read(agreement.key)).positions.yes).toBe(100000n);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.evaluate(() => { (window as any).rejectMarketSignature = false; });
    await dialog.getByRole('button', { name: 'Get quote', exact: true }).press('Enter');
    await expect(dialog.getByRole('button', { name: 'Confirm trade', exact: true })).toBeEnabled();
    await dialog.getByRole('button', { name: 'Confirm trade', exact: true }).press('Enter');
    await expect(dialog.getByRole('status')).toHaveText('Confirmed', { timeout: 20000 });
    expect((await chain.adapter(chain.trader).read(agreement.key)).positions.yes).toBe(50000n);
    await chain.execute(agreement);
    await dialog.getByRole('button', { name: 'Refresh', exact: true }).press('Enter');
    await expect(dialog.getByRole('button', { name: 'Resolve market', exact: true })).toBeEnabled();
    await dialog.getByRole('button', { name: 'Resolve market', exact: true }).press('Enter');
    await expect(dialog.getByRole('button', { name: 'Claim winnings', exact: true })).toBeEnabled({ timeout: 20000 });
    await dialog.getByRole('button', { name: 'Claim winnings', exact: true }).press('Enter');
    await expect(dialog.getByRole('status')).toHaveText('Confirmed', { timeout: 20000 });
    expect((await chain.adapter(chain.trader).read(agreement.key)).positions.yes).toBe(0n);
    await page.screenshot({ path: testInfo.outputPath('market-narrow.png'), fullPage: true });
    expect(errors).toEqual([]);
});
