import { test, expect } from '../helpers/fixtures';
import { stubBasemapTiles } from '../helpers/runtime';
import { applyLayout, createFromPlan, editorSave, editorClosed, editorCancel, storedAgreements, openStackAgreement, openAgreementActions } from '../helpers/agreements';
import { E2E_LENS_MEMBER_KEY } from '../helpers/mocks/shared-server';

test.describe('developer apartment funding authoring', () => {
  test.beforeEach(async ({ mockApi: page }) => { await stubBasemapTiles(page); });

  test('pastes a copied apartment link, saves drawings and round-trips at narrow width', async ({ mockApi: page }) => {
    test.setTimeout(120_000);
    await page.setViewportSize({ width: 390, height: 844 });
    const { layoutId } = await applyLayout(page);
    const initialEditor = await createFromPlan(page, layoutId, 'Apartment reservation plan');
    await editorCancel(initialEditor).click();
    await page.getByRole('button', { name: /Developer crowdfunding/i }).click();
    const editor = page.locator('dialog.agreement-editor-modal');
    await expect(editor.locator('[data-agreement-funding-form]')).toBeVisible();
    await editor.locator('[data-agreement-funding-target]').fill('1');
    await editor.locator('[data-agreement-funding-file]').setInputFiles({ name: 'terms.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7 investor terms') });
    const add = editor.locator('[data-apartment-add]');
    await add.click();
    await add.click();
    const rows = editor.locator('[data-apartment-unit]');
    await expect(rows).toHaveCount(2);
    const link = 'http://localhost:5680/?xray=1&xrayBuilding=new_york%3A%3Abuildings%3A%3Atower-1&unit=7%3A%3A1&suggested=1&access=point&at=40.7143%2C-74.0085%2C19';
    const first = rows.nth(0);
    await first.locator('[data-apartment="xrayBuilding"]').evaluate((node, url) => {
      const data = new DataTransfer();
      data.setData('text/plain', url);
      node.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData: data }));
    }, link);
    await expect(first.locator('[data-apartment="unit"]')).toHaveValue('7::1');
    await expect(first.locator('[data-apartment="at"]')).toHaveValue('40.7143,-74.0085,19');
    await first.locator('[data-apartment="unitId"]').fill('initial-id');
    await first.locator('[data-apartment="label"]').fill('Home A');
    await first.locator('[data-apartment="priceInput"]').fill('10.50');
    await first.locator('[data-apartment="depositInput"]').fill('1');
    await rows.nth(0).locator('[data-apartment-drawing]').setInputFiles({ name: 'a.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7 drawing A') });
    await rows.nth(1).locator('[data-apartment="unitId"]').fill('unit-b');
    await rows.nth(1).locator('[data-apartment="label"]').fill('Home B');
    await rows.nth(1).locator('[data-apartment="xrayBuilding"]').fill('zagreb::gdi-3d::building-2');
    await rows.nth(1).locator('[data-apartment="unit"]').fill('8::1');
    await rows.nth(1).locator('[data-apartment="at"]').fill('45.81,15.97,19');
    await rows.nth(1).locator('[data-apartment="priceInput"]').fill('1');
    await rows.nth(1).locator('[data-apartment="depositInput"]').fill('1');
    await rows.nth(1).locator('[data-apartment-drawing]').setInputFiles({ name: 'b.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7 drawing B') });
    await editor.locator('[data-apartments-project]').fill('fair-project');
    await editor.locator('[data-agreement-action="lens"]').click();
    // A crowdfunding round opens the Solana lens-set picker (f444a5c19) with no lens chosen.
    const lens = page.locator('.lens-modal');
    await lens.getByRole('textbox', { name: 'Paste a key' }).fill(E2E_LENS_MEMBER_KEY);
    await lens.getByRole('button', { name: 'Add', exact: true }).click();
    await expect(lens.getByRole('checkbox', { checked: true })).toHaveCount(1);
    await expect(lens.getByRole('checkbox', { name: /E2E lens member/ })).toBeChecked();
    await lens.locator('.lens-close-btn').press('Enter');
    await editor.locator('[data-agreement-deadline]').fill('2030-12-31');
    await first.locator('[data-apartment="unitId"]').fill('unit-a');
    await expect(editorSave(editor)).toBeEnabled();
    await editorSave(editor).press('Enter');
    await editorClosed(page);
    const [saved] = await storedAgreements(page);
    expect(saved.funding.apartments.units).toHaveLength(2);
    expect(saved.rule.lens).toEqual([E2E_LENS_MEMBER_KEY]);
    expect(saved.funding.apartments.units[0]).toMatchObject({ unitId: 'unit-a', unit: '7::1', drawing: { name: 'a.pdf' }, priceUsdcAtomic: '10500000' });
    const panel = await openStackAgreement(page);
    await openAgreementActions(page);
    await panel.locator('[data-agreement-action="edit"]').press('Enter');
    await expect(rows).toHaveCount(2);
    await expect(first.locator('[data-apartment="unit"]')).toHaveValue('7::1');
    await expect(first.locator('[data-apartment-drawing-name]')).toHaveText('a.pdf');
    await expect(rows.nth(1).locator('[data-apartment-drawing-name]')).toHaveText('b.pdf');
  });
});
