#!/usr/bin/env node
'use strict';

// Build production-only classic-script bundles from the marked script runs in index.html.
// Source files and the development index are never modified.
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const EXCLUDED_PATHS = new Set(['js/build-info.js']);
const STAGE_MARKER = '<!-- generated by frontend/build-static.cjs; static build stage v1 -->';
const ESBUILD_SEARCH_ROOT = path.join(__dirname, '..', 'backend');
let esbuild = null;

// esbuild is a backend devDependency, resolved from backend/ upwards (a deploy-only clone installs
// just that package at the repository root; see deploy-frontend.sh). Bundles are never shipped
// unminified: without esbuild the build stops.
function loadEsbuild() {
    if (esbuild) return esbuild;
    let resolved;
    try {
        resolved = require.resolve('esbuild', { paths: [ESBUILD_SEARCH_ROOT] });
    } catch (error) {
        throw new Error(`esbuild is required to minify the static bundles but cannot be resolved from ${ESBUILD_SEARCH_ROOT}. `
            + 'Install the backend dependencies (npm ci --prefix backend --include=dev) or the locked esbuild version.', { cause: error });
    }
    esbuild = require(resolved);
    return esbuild;
}

// One IIFE/UMD fragment in, the same expression minified out. Each fragment is minified on its own,
// so the source marker in front of it survives and an esbuild error names the file.
function minifyFragment(pathEntry, source) {
    const { transformSync } = loadEsbuild();
    try {
        return transformSync(source, { minify: true, target: 'es2020', legalComments: 'none', sourcefile: pathEntry }).code.trim();
    } catch (error) {
        throw new Error(`esbuild could not minify ${pathEntry}`, { cause: error });
    }
}

function readString(source, start) {
    const quote = source[start];
    let i = start + 1;
    let value = '';
    while (i < source.length) {
        const ch = source[i++];
        if (ch === quote) return { value, end: i };
        if (ch === '\\') {
            if (i >= source.length) throw new Error('Unterminated escaped script path in index.html');
            const escaped = source[i++];
            const map = { n: '\n', r: '\r', t: '\t' };
            value += Object.prototype.hasOwnProperty.call(map, escaped) ? map[escaped] : escaped;
        } else value += ch;
    }
    throw new Error('Unterminated script path in index.html');
}

function skipSpaceAndComments(source, cursor) {
    let i = cursor;
    while (i < source.length) {
        if (/\s/.test(source[i])) { i += 1; continue; }
        if (source.startsWith('//', i)) {
            const newline = source.indexOf('\n', i + 2);
            i = newline < 0 ? source.length : newline + 1;
            continue;
        }
        if (source.startsWith('/*', i)) {
            const end = source.indexOf('*/', i + 2);
            if (end < 0) throw new Error('Unterminated comment in index.html script list');
            i = end + 2;
            continue;
        }
        break;
    }
    return i;
}

function findScriptArrays(index) {
    const arrays = [];
    const call = /window\.writeVersionedLocalScripts\s*\(/g;
    let match;
    while ((match = call.exec(index))) {
        let cursor = skipSpaceAndComments(index, call.lastIndex);
        if (index[cursor] !== '[') throw new Error('Expected a script path array after writeVersionedLocalScripts(');
        const open = cursor;
        cursor += 1;
        const items = [];
        while (true) {
            cursor = skipSpaceAndComments(index, cursor);
            if (index[cursor] === ']') { cursor += 1; break; }
            if (index[cursor] !== '"' && index[cursor] !== "'") {
                throw new Error('Static build expects string-only writeVersionedLocalScripts arrays');
            }
            const item = readString(index, cursor);
            items.push({ value: item.value, start: cursor, end: item.end });
            cursor = skipSpaceAndComments(index, item.end);
            if (index[cursor] === ',') { cursor += 1; continue; }
            if (index[cursor] === ']') { cursor += 1; break; }
            throw new Error(`Expected comma or ] in writeVersionedLocalScripts array at byte ${cursor}`);
        }
        arrays.push({ start: open, end: cursor, items });
        call.lastIndex = cursor;
    }
    return arrays;
}

function findBundleGroups(index, arrays = findScriptArrays(index)) {
    const markers = [];
    const markerLine = /^[ \t]*\/\/[ \t]*bundle\b[^\r\n]*$/gm;
    let match;
    while ((match = markerLine.exec(index))) {
        const syntax = /^[ \t]*\/\/ bundle:(start|end) ([a-z][a-z0-9-]*)[ \t]*$/;
        const parsed = match[0].match(syntax);
        if (!parsed) throw new Error(`Malformed bundle marker: ${match[0].trim()}`);
        const array = arrays.find(candidate => match.index > candidate.start && markerLine.lastIndex <= candidate.end);
        if (!array) throw new Error(`Bundle marker is outside a writeVersionedLocalScripts array: ${parsed[2]}`);
        markers.push({ kind: parsed[1], name: parsed[2], start: match.index, end: markerLine.lastIndex, array });
    }

    const groups = [];
    const names = new Set();
    let open = null;
    for (const marker of markers) {
        if (marker.kind === 'start') {
            if (names.has(marker.name)) throw new Error(`Duplicate bundle name: ${marker.name}`);
            if (open) throw new Error(`Nested bundle markers: ${open.name} contains ${marker.name}`);
            names.add(marker.name);
            open = marker;
            continue;
        }
        if (!open) throw new Error(`Bundle end marker without a start: ${marker.name}`);
        if (open.name !== marker.name) throw new Error(`Mismatched bundle markers: ${open.name} ended by ${marker.name}`);
        if (open.array !== marker.array) throw new Error(`Bundle ${marker.name} crosses script arrays`);
        const first = open.array.items.findIndex(item => item.start > open.end);
        let last = -1;
        for (let i = 0; i < open.array.items.length; i += 1) {
            if (open.array.items[i].end < marker.start) last = i;
        }
        if (first < 0 || last < first) throw new Error(`Bundle ${marker.name} contains no scripts`);
        const items = open.array.items.slice(first, last + 1);
        if (items.length < 2) throw new Error(`Bundle ${marker.name} must contain at least two scripts`);
        groups.push({
            name: marker.name,
            // Query tokens are cache metadata, not source identities or part of the old hash input.
            paths: items.map(item => item.value.split('?')[0]),
            start: items[0].start,
            end: items[items.length - 1].end
        });
        open = null;
    }
    if (open) throw new Error(`Bundle start marker has no matching end: ${open.name}`);
    return groups;
}

function firstCodeIndex(source) {
    let i = source.charCodeAt(0) === 0xFEFF ? 1 : 0;
    while (i < source.length) {
        if (/\s/.test(source[i])) { i += 1; continue; }
        if (source.startsWith('//', i)) {
            const newline = source.indexOf('\n', i + 2);
            i = newline < 0 ? source.length : newline + 1;
            continue;
        }
        if (source.startsWith('/*', i)) {
            const end = source.indexOf('*/', i + 2);
            if (end < 0) break;
            i = end + 2;
            continue;
        }
        break;
    }
    return i;
}


function assertScopeIsolated(pathEntry, source, filename) {
    const file = pathEntry.split('?')[0];
    if (EXCLUDED_PATHS.has(file)) throw new Error(`Refusing to bundle excluded bootstrap script: ${pathEntry}`);
    if (/\bdocument\s*\.\s*(?:currentScript|write)\b/.test(source)) {
        throw new Error(`Refusing to bundle script that depends on document.currentScript/document.write: ${pathEntry}`);
    }
    const first = firstCodeIndex(source);
    const body = source.slice(first).trimEnd().replace(/;+\s*$/, '');
    if (source[first] !== '(' || !body.endsWith(')')) {
        throw new Error(`Allowlisted source must remain one parenthesized IIFE/UMD expression: ${pathEntry}`);
    }
    try {
        // Wrapping the entire trimmed file proves it is a single expression. Checking only its
        // first and last characters would accept an injected declaration between two IIFEs.
        new vm.Script(`(${body}\n)`, { filename });
    } catch (error) {
        throw new Error(`Allowlisted source must remain one parenthesized IIFE/UMD expression: ${pathEntry}`, { cause: error });
    }
}

function bundleSource(group, sourceRoot) {
    const fragments = group.paths.map(pathEntry => {
        const sourceFile = path.resolve(sourceRoot, pathEntry.split('?')[0]);
        if (!sourceFile.startsWith(`${path.resolve(sourceRoot)}${path.sep}`)) {
            throw new Error(`Bundle path escapes frontend source: ${pathEntry}`);
        }
        const source = fs.readFileSync(sourceFile, 'utf8');
        assertScopeIsolated(pathEntry, source, sourceFile);
        return `/* source: ${pathEntry} */\n;\n${minifyFragment(pathEntry, source)}\n;`;
    });
    const content = `${fragments.join('\n')}\n`;
    new vm.Script(content, { filename: `bundle:${group.name}` });
    return content;
}

function keepHashedBundlesCacheable(index) {
    const signature = 'function appendBuildToken(path) {';
    const first = index.indexOf(signature);
    if (first < 0 || index.indexOf(signature, first + signature.length) >= 0) {
        throw new Error('Expected one appendBuildToken(path) function in index.html');
    }
    const insertion = `${signature}\n                if (/^js\\/bundles\\/[^/]+\\.[a-f0-9]{16}\\.js$/.test(path)) return path;\n                if (/^(?:css\\/bundles\\/[^/]+\\.[a-f0-9]{16}\\.css|i18n\\/[^/]+\\.[a-f0-9]{16}\\.json)$/.test(path)) return path;`;
    return index.replace(signature, insertion);
}

function findCssFiles(index) {
    const match = /var cssFiles = \[([\s\S]*?)\];/.exec(index);
    if (!match) return [];
    return [...match[1].matchAll(/'([^']+)'/g)].map(item => item[1]);
}

function bundleCss(cssFiles, sourceRoot) {
    const content = cssFiles.map(entry => {
        const file = path.resolve(sourceRoot, entry.split('?')[0]);
        if (!file.startsWith(`${path.resolve(sourceRoot)}${path.sep}`)) throw new Error(`CSS path escapes frontend source: ${entry}`);
        let css = fs.readFileSync(file, 'utf8');
        const directory = path.posix.dirname(entry.split('?')[0]);
        css = css.replace(/url\(\s*(['"]?)([^)'"\s]+)\1\s*\)/g, (all, quote, value) => {
            if (/^(?:data:|https?:|\/|#)/.test(value)) return all;
            const resolved = path.posix.normalize(path.posix.join('../../', directory, value));
            return `url(${quote}${resolved}${quote})`;
        });
        return `/* source: ${entry} */\n${css}`;
    }).join('\n');
    const hash = crypto.createHash('sha256').update(content).digest('hex').slice(0, 16);
    return { path: `css/bundles/app.${hash}.css`, content };
}

function markStageIndex(index) {
    const doctype = /<!doctype\s+html\s*>/i;
    if (doctype.test(index)) return index.replace(doctype, match => `${match}\n${STAGE_MARKER}`);
    return `${STAGE_MARKER}\n${index}`;
}

function hashedAssets(sourceRoot, outputDir, directory, extension, include) {
    const paths = {};
    if (!fs.existsSync(path.join(sourceRoot, directory))) return paths;
    for (const file of fs.readdirSync(path.join(sourceRoot, directory))) {
        const relative = `${directory}/${file}`;
        if (!file.endsWith(extension) || !include(relative)) continue;
        const content = fs.readFileSync(path.join(sourceRoot, relative));
        const hash = crypto.createHash('sha256').update(content).digest('hex').slice(0, 16);
        const target = `${relative.slice(0, -extension.length)}.${hash}${extension}`;
        fs.writeFileSync(path.join(outputDir, target), content);
        paths[relative] = target;
    }
    return paths;
}

function countPaths(arrays) { return arrays.reduce((count, array) => count + array.items.length, 0); }

function prepareOutputDirectory(outputDir) {
    if (fs.existsSync(outputDir)) {
        const stat = fs.lstatSync(outputDir);
        if (!stat.isDirectory() || stat.isSymbolicLink()) {
            throw new Error('Static build output must be a real directory');
        }
        const entries = fs.readdirSync(outputDir);
        const isOwnedStage = entries.length > 0
            && entries.includes('index.html')
            && fs.lstatSync(path.join(outputDir, 'index.html')).isFile()
            && fs.readFileSync(path.join(outputDir, 'index.html'), 'utf8').includes(STAGE_MARKER);
        if (entries.length > 0 && !isOwnedStage) {
            throw new Error('Refusing to replace a non-empty output directory without the static-build marker');
        }
        fs.rmSync(outputDir, { recursive: true, force: true });
    }
    fs.mkdirSync(outputDir, { recursive: true });
    // Establish ownership immediately so a partial failed build can safely be retried.
    fs.writeFileSync(path.join(outputDir, 'index.html'), `${STAGE_MARKER}\n`);
}

function buildStatic(sourceRoot, outputDir) {
    sourceRoot = path.resolve(sourceRoot);
    outputDir = path.resolve(outputDir);
    if (sourceRoot === outputDir || sourceRoot.startsWith(`${outputDir}${path.sep}`)
        || outputDir.startsWith(`${sourceRoot}${path.sep}`)) {
        throw new Error('Output directory must be separate from the frontend source directory');
    }
    const indexPath = path.join(sourceRoot, 'index.html');
    const originalIndex = fs.readFileSync(indexPath, 'utf8');
    const arrays = findScriptArrays(originalIndex);
    if (!arrays.length) throw new Error('No writeVersionedLocalScripts arrays found in index.html');
    const groups = findBundleGroups(originalIndex, arrays);
    if (!groups.length) throw new Error('No marked bundle groups found in index.html');
    const beforeCount = countPaths(arrays);
    const replacements = [];
    const outputBundles = [];
    const cssFiles = findCssFiles(originalIndex);
    const cssBundle = cssFiles.length ? bundleCss(cssFiles, sourceRoot) : null;

    for (const group of groups) {
        const content = bundleSource(group, sourceRoot);
        const hash = crypto.createHash('sha256')
            .update(group.name).update('\0').update(group.paths.join('\0')).update('\0').update(content)
            .digest('hex').slice(0, 16);
        const bundlePath = `js/bundles/${group.name}.${hash}.js`;
        replacements.push({ start: group.start, end: group.end, value: bundlePath });
        outputBundles.push({ path: bundlePath, content });
    }

    let rewrittenIndex = originalIndex;
    replacements.sort((a, b) => b.start - a.start).forEach(replacement => {
        rewrittenIndex = `${rewrittenIndex.slice(0, replacement.start)}'${replacement.value}'${rewrittenIndex.slice(replacement.end)}`;
    });

    rewrittenIndex = markStageIndex(keepHashedBundlesCacheable(rewrittenIndex));
    if (cssBundle) rewrittenIndex = rewrittenIndex.replace(/var cssFiles = \[[\s\S]*?\];/, `var cssFiles = ['${cssBundle.path}'];`);

    prepareOutputDirectory(outputDir);
    // data/city-configs.js is the source every city file is generated from; the browser never loads it.
    const cityConfigsSource = path.join(sourceRoot, 'data', 'city-configs.js');
    fs.cpSync(sourceRoot, outputDir, {
        recursive: true,
        filter: source => path.basename(source) !== 'build-static.cjs' && path.resolve(source) !== indexPath
            && path.resolve(source) !== cityConfigsSource
    });
    const bundleDir = path.join(outputDir, 'js/bundles');
    fs.mkdirSync(bundleDir, { recursive: true });
    for (const bundle of outputBundles) {
        fs.writeFileSync(path.join(outputDir, bundle.path), bundle.content);
    }
    if (cssBundle) {
        fs.mkdirSync(path.join(outputDir, 'css/bundles'), { recursive: true });
        fs.writeFileSync(path.join(outputDir, cssBundle.path), cssBundle.content);
    }
    const bootStyles = new Set(cssFiles.map(file => file.split('?')[0]));
    const styles = hashedAssets(sourceRoot, outputDir, 'css', '.css', file => !bootStyles.has(file));
    const languages = hashedAssets(sourceRoot, outputDir, 'i18n', '.json', () => true);
    const assets = Object.fromEntries(Object.entries(languages).map(([file, url]) => [path.basename(file, '.json'), url]));
    // The compact route can show progress and offer retry before loading a full dictionary.
    const planEntry = path.join(outputDir, 'plan-entry.html');
    if (fs.existsSync(planEntry)) {
        const words = {};
        for (const [lang, url] of Object.entries(assets)) {
            const dictionary = JSON.parse(fs.readFileSync(path.join(outputDir, url), 'utf8'));
            words[lang] = {
                loading: dictionary.common?.busy?.loading,
                retry: dictionary.bets?.retry,
                failed: dictionary.proposals?.share?.named?.openFailed,
                heading: dictionary.planDialog?.openPlan,
                back: dictionary.pageHeader?.backToMap
            };
        }
        const page = fs.readFileSync(planEntry, 'utf8').replace('id="plan-entry-words">{}',
            'id="plan-entry-words">' + JSON.stringify(words).replace(/</g, '\\u003c'));
        fs.writeFileSync(planEntry, page);
    }
    rewrittenIndex = rewrittenIndex.replace('</head>', `<script>window.__I18N_ASSETS=${JSON.stringify(assets)};window.__CSS_ASSETS=${JSON.stringify(styles)};</script></head>`);
    fs.writeFileSync(path.join(outputDir, 'index.html'), rewrittenIndex);

    const afterArrays = findScriptArrays(rewrittenIndex);
    const afterCount = countPaths(afterArrays);
    const reduction = beforeCount - afterCount;
    return { beforeCount, afterCount, reduction, bundles: [...outputBundles.map(item => item.path), ...(cssBundle ? [cssBundle.path] : [])] };
}

if (require.main === module) {
    const outputDir = process.argv[2];
    const sourceRoot = process.argv[3] || __dirname;
    if (!outputDir) {
        console.error('Usage: node frontend/build-static.cjs <output-directory> [frontend-source-directory]');
        process.exit(2);
    }
    const result = buildStatic(sourceRoot, outputDir);
    console.log(`Static frontend staged at ${path.resolve(outputDir)}`);
    console.log(`Classic script paths: ${result.beforeCount} -> ${result.afterCount} (${result.reduction} requests removed; ${result.bundles.length} bundles)`);
    result.bundles.forEach(bundle => console.log(`  ${bundle}`));
}

module.exports = { EXCLUDED_PATHS, findScriptArrays, findBundleGroups, assertScopeIsolated, buildStatic };
