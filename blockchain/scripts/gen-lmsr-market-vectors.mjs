// Writes forge-test/fixtures/LmsrMarketVectors.sol: a sequence of buys and sells on one yes/no market
// with what frontend/js/bets/lmsr.js quotes for each (buyCost, sellReturn) at the state it reaches.
// forge-test/AgreementMarkets.t.sol replays the sequence on a Gnosis LMSR market maker and checks
// that it charges and pays the same within rounding. Usage: node scripts/gen-lmsr-market-vectors.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const lmsr = createRequire(import.meta.url)(path.join(here, '../../frontend/js/bets/lmsr.js'));
const out = path.join(here, '../forge-test/fixtures/LmsrMarketVectors.sol');

// b = 5 USDC in atomic units (6 decimals), the liquidity agreement markets open with (backend/agents/bettor.js).
const B = 5_000_000n;
const USDC = 1_000_000n;
// [side, buy (true) or sell (false), shares]: small and large trades, both sides, prices near 0 and 1.
const SEQUENCE = [
    ['yes', true, 1n],
    ['yes', true, USDC],
    ['no', true, 5n * USDC / 2n],
    ['yes', true, 20n * USDC],
    ['yes', false, 5n * USDC],
    ['no', true, 1n],
    ['no', true, 50n * USDC],
    ['no', false, 10n * USDC],
    ['yes', true, 123_456_789n],
    ['yes', false, USDC],
    ['no', true, 7n],
    ['yes', false, 100n * USDC]
];

let qYes = 0n;
let qNo = 0n;
const rows = SEQUENCE.map(([side, buy, shares]) => {
    const amount = buy ? lmsr.buyCost(B, qYes, qNo, side, shares) : lmsr.sellReturn(B, qYes, qNo, side, shares);
    const row = { side: side === 'yes' ? 1 : 0, buy, shares, qYes, qNo, amount };
    const delta = buy ? shares : -shares;
    if (side === 'yes') qYes += delta; else qNo += delta;
    return row;
});

const lines = rows.map((r, i) => `        t[${i}] = Trade(${r.side}, ${r.buy}, ${r.shares}, ${r.qYes}, ${r.qNo}, ${r.amount});`);
writeFileSync(out, `// SPDX-License-Identifier: MIT
// Generated by scripts/gen-lmsr-market-vectors.mjs from frontend/js/bets/lmsr.js: a sequence of trades
// on one market with b = ${B} and what lmsr.js quotes for each at the state before it (qYes, qNo).
// Do not edit by hand.
pragma solidity ^0.8.20;

library LmsrMarketVectors {
    uint256 internal constant B = ${B};

    /// side 1 = YES, 0 = NO; amount is buyCost for a buy and sellReturn for a sell, in atomic units.
    struct Trade {
        uint8 side;
        bool buy;
        uint256 shares;
        uint256 qYes;
        uint256 qNo;
        uint256 amount;
    }

    function trades() internal pure returns (Trade[] memory t) {
        t = new Trade[](${rows.length});
${lines.join('\n')}
    }
}
`);
console.error(`[${new Date().toISOString()}] wrote ${rows.length} trades to ${path.relative(process.cwd(), out)}`);
