// Renders backend/test/fixtures/lmsr-vectors.json as a Rust array so the program's unit tests pin
// the port to the JavaScript reference without a JSON dependency. Run without arguments to see the
// usage; --write regenerates programs/proposal_market/src/lmsr_vectors.rs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '../../../backend/test/fixtures/lmsr-vectors.json');
const target = join(here, '../programs/proposal_market/src/lmsr_vectors.rs');

if (!process.argv.includes('--write')) {
    console.log(`Usage: node scripts/gen-lmsr-vectors.mjs --write\n  reads ${source}\n  writes ${target}`);
    process.exit(0);
}
const data = JSON.parse(readFileSync(source, 'utf8'));
const vectors = Array.isArray(data) ? data : data.vectors;
const lines = vectors.map(v => `    ("${v.fn}", &[${v.args.map(a => `"${a}"`).join(', ')}], "${v.expected}"),`);
const body = `// Generated by scripts/gen-lmsr-vectors.mjs from backend/test/fixtures/lmsr-vectors.json: every
// (function, arguments, expected) the Rust port must reproduce exactly. Do not edit by hand.
pub const VECTORS: &[(&str, &[&str], &str)] = &[
${lines.join('\n')}
];
`;
writeFileSync(target, body);
console.log(`[${new Date().toISOString()}] wrote ${vectors.length} vectors to ${target}`);
