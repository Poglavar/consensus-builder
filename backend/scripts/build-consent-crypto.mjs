#!/usr/bin/env node
// Build the tiny browser/Node crypto helpers used by consent records: SHA-256 fingerprints and
// Ed25519 signature verification for lens attestations and owner decisions.
// Rebuild from the pinned backend dependencies with: node backend/scripts/build-consent-crypto.mjs
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '../..');
const backendDir = path.resolve(repoRoot, 'backend');
const require = createRequire(import.meta.url);
const esbuild = require('../node_modules/esbuild');
const esbuildVersion = JSON.parse(await readFile(require.resolve('../node_modules/esbuild/package.json'), 'utf8')).version;
if (esbuildVersion !== '0.28.2') throw new Error(`Expected esbuild 0.28.2, found ${esbuildVersion}`);

// The package directory of an installed entry point, after checking its exact version.
async function pinnedPackage(entry, name, version) {
    const dir = path.dirname(require.resolve(entry, { paths: [backendDir] }));
    const found = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8')).version;
    if (found !== version) throw new Error(`Expected ${name} ${version}, found ${found}`);
    return dir;
}

async function bundle({ name, version, packageDir, globalName, purpose, entryName, source, outputDir, fileName }) {
    const result = await esbuild.build({
        stdin: { contents: source, resolveDir: backendDir, sourcefile: entryName, loader: 'js' },
        bundle: true,
        write: false,
        platform: 'browser',
        format: 'cjs',
        target: ['es2020'],
        legalComments: 'none',
        minify: true
    });
    const bundled = result.outputFiles[0].text;
    const generated = `/* Generated by backend/scripts/build-consent-crypto.mjs from ${name} ${version}.\n * Purpose: ${purpose}\n * Do not edit by hand; rebuild with the command documented in that script.\n * ${name} is MIT licensed; see LICENSE.txt.\n */\n(function (root, factory) {\n    if (typeof module === 'object' && module.exports) module.exports = factory();\n    else root.${globalName} = factory();\n}(typeof globalThis !== 'undefined' ? globalThis : this, function () {\n    var module = { exports: {} };\n${bundled}\n    return module.exports;\n}));\n`;
    const outputPath = path.join(repoRoot, outputDir, fileName);
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, generated);
    await writeFile(path.join(repoRoot, outputDir, 'LICENSE.txt'), await readFile(path.join(packageDir, 'LICENSE')));
    console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${Buffer.byteLength(generated)} bytes)`);
}

await bundle({
    name: '@noble/hashes',
    version: '1.8.0',
    packageDir: await pinnedPackage('@noble/hashes/sha2.js', '@noble/hashes', '1.8.0'),
    globalName: '__consentSha256',
    purpose: 'synchronous SHA-256 hex fingerprints for browser and Node consent code.',
    entryName: 'consent-sha256-entry.js',
    outputDir: 'frontend/vendor/noble-hashes-1.8.0',
    fileName: 'sha256.js',
    source: `import { sha256 } from '@noble/hashes/sha2.js';

export function sha256Hex(text) {
    if (typeof text !== 'string') throw new TypeError('sha256Hex expects a string');
    return Array.from(sha256(new TextEncoder().encode(text)), byte => byte.toString(16).padStart(2, '0')).join('');
}
`
});

// Strict RFC 8032 / FIPS 186-5 decoding (zip215: false) gives every key and signature one encoding,
// so the browser, the lens member and Node tests accept exactly the same signatures.
await bundle({
    name: '@noble/curves',
    version: '1.2.0',
    packageDir: await pinnedPackage('@noble/curves/ed25519', '@noble/curves', '1.2.0'),
    globalName: '__consentEd25519',
    purpose: 'synchronous Ed25519 verification of lens attestations and owner decisions.',
    entryName: 'consent-ed25519-entry.js',
    outputDir: 'frontend/vendor/noble-curves-1.2.0',
    fileName: 'ed25519.js',
    source: `import { ed25519 } from '@noble/curves/ed25519';

export function verify(signature, message, publicKey) {
    try {
        return ed25519.verify(signature, message, publicKey, { zip215: false }) === true;
    } catch (_) {
        return false;
    }
}
`
});
