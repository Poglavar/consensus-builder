#!/usr/bin/env node
// Build the tiny browser/Node SHA-256 helper used to fingerprint consent records.
// Rebuild from the pinned backend dependencies with: node backend/scripts/build-consent-crypto.mjs
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '../..');
const require = createRequire(import.meta.url);
const esbuild = require('../node_modules/esbuild');
const nobleEntryPath = require.resolve('@noble/hashes/sha2.js', { paths: [path.resolve(repoRoot, 'backend')] });
const nobleDir = path.dirname(nobleEntryPath);
const noblePackagePath = path.join(nobleDir, 'package.json');
const noblePackage = JSON.parse(await readFile(noblePackagePath, 'utf8'));
if (noblePackage.version !== '1.8.0') throw new Error(`Expected @noble/hashes 1.8.0, found ${noblePackage.version}`);
const esbuildVersion = JSON.parse(await readFile(require.resolve('../node_modules/esbuild/package.json'), 'utf8')).version;
if (esbuildVersion !== '0.28.2') throw new Error(`Expected esbuild 0.28.2, found ${esbuildVersion}`);

const outputDir = path.join(repoRoot, 'frontend/vendor/noble-hashes-1.8.0');
const outputPath = path.join(outputDir, 'sha256.js');
const source = `import { sha256 } from '@noble/hashes/sha2.js';

export function sha256Hex(text) {
    if (typeof text !== 'string') throw new TypeError('sha256Hex expects a string');
    return Array.from(sha256(new TextEncoder().encode(text)), byte => byte.toString(16).padStart(2, '0')).join('');
}
`;

const result = await esbuild.build({
    stdin: { contents: source, resolveDir: path.join(repoRoot, 'backend'), sourcefile: 'consent-sha256-entry.js', loader: 'js' },
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'cjs',
    target: ['es2020'],
    legalComments: 'none',
    minify: true
});
const bundled = result.outputFiles[0].text;
const generated = `/* Generated by backend/scripts/build-consent-crypto.mjs from @noble/hashes 1.8.0.\n * Purpose: synchronous SHA-256 hex fingerprints for browser and Node consent code.\n * Do not edit by hand; rebuild with the command documented in that script.\n * @noble/hashes is MIT licensed; see LICENSE.txt.\n */\n(function (root, factory) {\n    if (typeof module === 'object' && module.exports) module.exports = factory();\n    else root.__consentSha256 = factory();\n}(typeof globalThis !== 'undefined' ? globalThis : this, function () {\n    var module = { exports: {} };\n${bundled}\n    return module.exports;\n}));\n`;

await mkdir(outputDir, { recursive: true });
await writeFile(outputPath, generated);
await writeFile(path.join(outputDir, 'LICENSE.txt'), await readFile(path.join(nobleDir, 'LICENSE')));
console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${Buffer.byteLength(generated)} bytes)`);
