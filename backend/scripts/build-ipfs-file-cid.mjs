#!/usr/bin/env node
// Bundle the synchronous UnixFS root-CID helper for browser and CommonJS consumers.
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '../..');
const backendDir = path.resolve(repoRoot, 'backend');
const require = createRequire(import.meta.url);
const esbuild = require('../node_modules/esbuild');

async function packageVersion(name) {
    let directory = path.dirname(fileURLToPath(import.meta.resolve(name)));
    while (true) {
        try {
            const pkg = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
            if (pkg.name === name) return pkg.version;
        } catch (_) { /* keep walking up to the package root */ }
        const parent = path.dirname(directory);
        if (parent === directory) throw new Error(`Could not locate ${name}/package.json`);
        directory = parent;
    }
}

const versions = {
    esbuild: '0.28.2',
    '@ipld/dag-pb': '4.2.0',
    'ipfs-unixfs': '13.1.2',
    multiformats: '14.0.5'
};
for (const [name, expected] of Object.entries(versions)) {
    const actual = name === 'esbuild'
        ? JSON.parse(await readFile(require.resolve('../node_modules/esbuild/package.json'), 'utf8')).version
        : await packageVersion(name);
    if (actual !== expected) throw new Error(`Expected ${name} ${expected}, found ${actual}`);
}

const result = await esbuild.build({
    absWorkingDir: backendDir,
    entryPoints: [path.join(backendDir, 'lib/ipfs-file-cid-entry.mjs')],
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'cjs',
    target: ['es2020'],
    metafile: true,
    legalComments: 'none',
    minify: true
});
const bundled = result.outputFiles[0].text;
const bundledPackages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
    const segments = input.split(/[\\/]/);
    const modulesIndex = segments.lastIndexOf('node_modules');
    if (modulesIndex < 0 || modulesIndex + 1 >= segments.length) continue;
    const packageSegments = segments[modulesIndex + 1].startsWith('@')
        ? segments.slice(modulesIndex + 1, modulesIndex + 3)
        : segments.slice(modulesIndex + 1, modulesIndex + 2);
    const packageName = packageSegments.join('/');
    const packageRoot = path.resolve(backendDir, ...segments.slice(0, modulesIndex + 1), ...packageSegments);
    if (bundledPackages.has(packageName)) continue;
    const metadata = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'));
    const files = await readdir(packageRoot);
    const licenseFiles = files.filter(file => /^(license|notice|copying)(?:\.|$)/i.test(file)).sort();
    const licenseTexts = [];
    for (const file of licenseFiles) {
        licenseTexts.push({ file, text: (await readFile(path.join(packageRoot, file), 'utf8')).trim() });
    }
    bundledPackages.set(packageName, {
        version: metadata.version,
        license: metadata.license || 'License not declared in package metadata',
        licenseTexts
    });
}
const thirdPartyNotices = [
    'Third-party notices for the generated IPFS file-CID browser bundle.',
    'Generated by backend/scripts/build-ipfs-file-cid.mjs from the exact bundled package inputs.',
    'Packages may be used under the license expression listed below. Where a package ships a LICENSE or NOTICE file, its text is reproduced verbatim.'
];
for (const [name, metadata] of [...bundledPackages].sort(([left], [right]) => left.localeCompare(right))) {
    thirdPartyNotices.push('', `${name} ${metadata.version}`, `License: ${metadata.license}`);
    for (const licenseFile of metadata.licenseTexts) {
        thirdPartyNotices.push('', `--- ${name}/${licenseFile.file} ---`, licenseFile.text);
    }
    if (!metadata.licenseTexts.length && metadata.license === 'Apache-2.0 OR MIT') {
        thirdPartyNotices.push(
            'The npm package includes no license text file; its package metadata declares this dual-license option.',
            'Apache-2.0: https://spdx.org/licenses/Apache-2.0.html',
            'MIT: https://spdx.org/licenses/MIT.html'
        );
    }
}
const generated = `/* Generated by backend/scripts/build-ipfs-file-cid.mjs.
 * Bundles the dependencies listed in THIRD_PARTY_NOTICES.txt.
 * Do not edit by hand; rebuild with: node backend/scripts/build-ipfs-file-cid.mjs
 */
(function (root, factory) {
    if (typeof module === 'object' && module.exports) module.exports = factory();
    else root.IpfsFileCid = factory();
}(typeof globalThis !== 'undefined' ? globalThis : this, function () {
    var module = { exports: {} };
${bundled}
    return module.exports;
}));
`;
const outputPath = path.join(repoRoot, 'frontend/vendor/ipfs-file-cid/ipfs-file-cid.js');
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
const noticePath = path.join(repoRoot, 'frontend/vendor/ipfs-file-cid/THIRD_PARTY_NOTICES.txt');
await writeFile(noticePath, `${thirdPartyNotices.join('\n')}\n`);
console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${Buffer.byteLength(generated)} bytes)`);
console.log(`Wrote ${path.relative(repoRoot, noticePath)} (${Buffer.byteLength(thirdPartyNotices.join('\n'))} bytes)`);
