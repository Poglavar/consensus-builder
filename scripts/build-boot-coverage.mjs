#!/usr/bin/env node
// Derives frontend/data/boot-coverage.js from frontend/data/world-coverage.json: the part of the
// coverage the app needs before anything else runs, to decide which city a view boots in
// (WorldCoverage.jurisdictionAt, location-first.md). That is every live city's centre and radius and
// the outlines of the countrywide-live countries (Croatia), ~1/20 of the full JSON, loaded as a
// classic script so city-config.js can read it synchronously. Its liveCitiesAt answers equal the
// full JSON's (backend/test/boot-coverage.test.js). build-world-coverage.mjs runs this after it
// writes the JSON; run it by hand only after editing the JSON some other way.
//
// Usage: node scripts/build-boot-coverage.mjs --run [--in path] [--out path]

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULTS = {
    input: path.join(REPO, 'frontend/data/world-coverage.json'),
    out: path.join(REPO, 'frontend/data/boot-coverage.js')
};

// The subset, in world-coverage.json's own shape so WorldCoverage.create reads it unchanged.
export function bootCoverage(coverage) {
    return {
        schemaVersion: coverage.schemaVersion,
        liveCities: coverage.liveCities.map(city => ({
            id: city.id, cc: city.cc, lat: city.lat, lon: city.lon,
            ...(city.radiusKm != null ? { radiusKm: city.radiusKm } : {})
        })),
        countries: coverage.countries.filter(country => country.tier === 'live')
            .map(country => ({ cc: country.cc, name: country.name, tier: country.tier, center: country.center, rings: country.rings })),
        cities: []
    };
}

export function bootCoverageScript(coverage) {
    return '// Generated by scripts/build-boot-coverage.mjs from world-coverage.json; do not edit.\n'
        + '// The coverage a view needs to pick its city before the app boots (location-first.md).\n'
        + `(function (root) { root.BOOT_COVERAGE = ${JSON.stringify(bootCoverage(coverage))}; })(typeof self !== 'undefined' ? self : this);\n`;
}

export function writeBootCoverage({ input = DEFAULTS.input, out = DEFAULTS.out } = {}) {
    const script = bootCoverageScript(JSON.parse(readFileSync(input, 'utf8')));
    writeFileSync(out, script);
    return { out, bytes: script.length };
}

function main(argv) {
    if (!argv.includes('--run') || argv.includes('--help')) {
        console.log('Usage: node scripts/build-boot-coverage.mjs --run [--in frontend/data/world-coverage.json] [--out frontend/data/boot-coverage.js]');
        return;
    }
    const opt = name => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
    const result = writeBootCoverage({
        input: path.resolve(opt('--in') || DEFAULTS.input),
        out: path.resolve(opt('--out') || DEFAULTS.out)
    });
    console.log(`[${new Date().toISOString()}] wrote ${path.relative(REPO, result.out)} (${(result.bytes / 1024).toFixed(1)} KB)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main(process.argv.slice(2));
}
