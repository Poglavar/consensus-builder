"""Write an area rate table: the generic file js/economic-sources.js's `area-rates` adapter reads.

An area rate table is a dataset's rates per published area (a local authority, a district, a value
zone), keyed by the area's code in an area layer (data/uk-economic-areas.js `lad`, …). Any country's
per-area statistics (land values, rents, development charges) take this shape; only the reader of the
source dataset is specific. The written file registers itself as window.EconomicAreaRates[id] in the
browser and exports the table under node. One area or city a line, so a rebuild diffs by row.

table = {
  'id': source id, 'name': readable name, 'url': the source document (https), 'licence': …,
  'layer': area layer id, 'currency': ISO 4217, 'asOf': 'YYYY-MM-DD' (the source's own date),
  'rates': [{'metric', 'unit', 'basis', 'field': the area row's amount field,
             'note': scope text, '{field}' placeholders filled from the area row}],
  'areas': {code: {'name': …, field: amount, …}},
  'cities': {cityId: code} (optional: the area a city stands for where a location gives none;
             without it the area under the city's map centre)
}
"""
import json


def write_area_rate_table(path, table, comment, generator):
    """Write `table` to `path` as a UMD script; `comment` is the file's purpose, one or more lines."""
    assert table['areas'], 'an area rate table needs areas'
    for rate in table['rates']:
        assert all(rate['field'] in row for row in table['areas'].values()), f"an area lacks {rate['field']}"
    head = {key: value for key, value in table.items() if key not in ('areas', 'cities')}
    rows = lambda mapping: ',\n'.join(f'    {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}'
                                      for key, value in sorted(mapping.items()))
    body = json.dumps(head, indent=2, ensure_ascii=False)[:-2] + f',\n  "areas": {{\n{rows(table["areas"])}\n  }}'
    if table.get('cities'):
        body += f',\n  "cities": {{\n{rows(table["cities"])}\n  }}'
    lines = ''.join(f'// {line}\n' for line in (f'GENERATED by {generator}; do not edit. ' + comment).split('\n'))
    with open(path, 'w', encoding='utf-8') as out:
        out.write(lines + '(function (root, data) {\n'
                  "    if (typeof module === 'object' && module.exports) module.exports = data;\n"
                  '    if (root) (root.EconomicAreaRates = root.EconomicAreaRates || {})[data.id] = data;\n'
                  "})(typeof window !== 'undefined' ? window : null, " + body + '\n});\n')
