#!/usr/bin/env node
// Splits frontend/data/city-configs.js (every city, full; the source of truth) into what the browser
// loads: frontend/data/city-index.js, every city's light configuration in one script, and
// frontend/data/cities/<id>.js, one city's full configuration, which js/city-config.js writes into
// the page for the city it runs in. Both are committed; backend/test/city-files.test.js fails when
// they are stale. The row format is frontend/js/city-light-config.js, and the builder checks that
// every row expands back to its light configuration before writing anything.
//
// Usage: node scripts/build-city-files.mjs --run [--check]    (--check: list stale files, write nothing)

import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CITY_CONFIGS_FILE, parseCityConfigs } from './lib/city-configs.mjs';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CITY_FILE_PATHS = Object.freeze({
    source: CITY_CONFIGS_FILE,
    index: 'frontend/data/city-index.js',
    cities: 'frontend/data/cities'
});
const lightConfig = createRequire(import.meta.url)('../frontend/js/city-light-config.js');
const HEADER = '// Generated by scripts/build-city-files.mjs from data/city-configs.js; do not edit.\n';
const ROOT_EXPR = "typeof window !== 'undefined' ? window : globalThis";

// A JS literal of the value: JSON, with Infinity (parcelZoomRange.max) written back as the keyword.
function literal(value) {
    return JSON.stringify(value, (_key, item) => item === Infinity ? '@@Infinity@@' : item === -Infinity ? '@@-Infinity@@' : item)
        .replace(/"@@Infinity@@"/g, 'Infinity').replace(/"@@-Infinity@@"/g, '-Infinity');
}

// The generated files for a city-configs.js source text: Map of repo-relative path -> content.
export function buildCityFiles(source) {
    const configs = parseCityConfigs(source);
    const ids = Object.keys(configs);
    for (const id of ids) if (!/^[a-z0-9_]+$/.test(id)) throw new Error(`city id "${id}" cannot name a file`);
    const index = lightConfig.pack(configs);
    const rows = new Map(index.rows.map(row => [row[0], row]));
    for (const id of ids) {
        const expanded = lightConfig.expand(index, rows.get(id));
        if (lightConfig.stable(expanded) !== lightConfig.stable(lightConfig.lightOf(configs[id]))) {
            throw new Error(`city ${id}: its index row does not expand to its light configuration`);
        }
    }
    const files = new Map();
    files.set(CITY_FILE_PATHS.index, `${HEADER}// Every city's light configuration (rows of js/city-light-config.js); the current city's full one is data/cities/<id>.js.\n`
        + `(function (root) { root.__cityIndex = ${literal(index)}; })(${ROOT_EXPR});\n`);
    for (const id of ids) {
        files.set(`${CITY_FILE_PATHS.cities}/${id}.js`, `${HEADER}(function (root) { (root.__cityConfigs = root.__cityConfigs || {})[${JSON.stringify(id)}] = ${literal(configs[id])}; })(${ROOT_EXPR});\n`);
    }
    return { files, cityCount: ids.length, indexBytes: files.get(CITY_FILE_PATHS.index).length };
}

// What differs between the generated files and the repo: stale (missing or different) and extra
// (files in data/cities/ that no city owns).
export function staleCityFiles(root = REPO) {
    const { files } = buildCityFiles(readFileSync(path.join(root, CITY_FILE_PATHS.source), 'utf8'));
    const stale = [];
    for (const [file, content] of files) {
        const full = path.join(root, file);
        if (!existsSync(full) || readFileSync(full, 'utf8') !== content) stale.push(file);
    }
    const dir = path.join(root, CITY_FILE_PATHS.cities);
    const extra = existsSync(dir)
        ? readdirSync(dir).filter(name => name.endsWith('.js') && !files.has(`${CITY_FILE_PATHS.cities}/${name}`)).map(name => `${CITY_FILE_PATHS.cities}/${name}`)
        : [];
    return { stale, extra, files };
}

export function writeCityFiles(root = REPO) {
    const { stale, extra, files } = staleCityFiles(root);
    mkdirSync(path.join(root, CITY_FILE_PATHS.cities), { recursive: true });
    for (const file of stale) writeFileSync(path.join(root, file), files.get(file));
    for (const file of extra) unlinkSync(path.join(root, file));
    return { written: stale.length, removed: extra.length, total: files.size };
}

function main(argv) {
    if (!argv.includes('--run') || argv.includes('--help')) {
        console.log('Usage: node scripts/build-city-files.mjs --run [--check]');
        return;
    }
    const stamp = () => `[${new Date().toISOString()}]`;
    if (argv.includes('--check')) {
        const { stale, extra } = staleCityFiles();
        if (!stale.length && !extra.length) { console.log(`${stamp()} city files are current`); return; }
        for (const file of stale) console.log(`${stamp()} stale: ${file}`);
        for (const file of extra) console.log(`${stamp()} extra: ${file}`);
        process.exitCode = 1;
        return;
    }
    const result = writeCityFiles();
    console.log(`${stamp()} wrote ${result.written} and removed ${result.removed} of ${result.total} city files (${CITY_FILE_PATHS.index}, ${CITY_FILE_PATHS.cities}/)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main(process.argv.slice(2));
}
