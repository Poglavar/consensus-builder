#!/usr/bin/env python3
"""Generate ignored browser RPC maps from backend/.env without printing provider URLs."""

import argparse
import json
import os
from pathlib import Path
import re
from urllib.parse import urlparse


ENV_KEYS = (
    'SOLANA_RPC_URL',
    'SOLANA_DEVNET_RPC_URL',
    'SOLANA_MAINNET_RPC_URL',
    'SOLANA_TESTNET_RPC_URL',
    'SOLANA_PROGRAM_ACCOUNTS_RPC_URL',
    'SOLANA_PROGRAM_ACCOUNTS_MAINNET_RPC_URL',
    'SOLANA_PROGRAM_ACCOUNTS_TESTNET_RPC_URL',
)


def read_env_file(path):
    values = {}
    if not path.exists():
        return values
    for line in path.read_text().splitlines():
        match = re.match(r"^\s*(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=\s*(.*?)\s*$", line)
        if not match:
            continue
        key, value = match.groups()
        if key not in ENV_KEYS:
            continue
        value = value.split(' #', 1)[0].strip().strip("\"'")
        values[key] = value
    return values


def validate_url(value, name):
    if not value:
        return None
    parsed = urlparse(value)
    if parsed.scheme not in ('http', 'https') or not parsed.netloc:
        raise ValueError(f'{name} must be an HTTP(S) endpoint')
    return value


def build_config(values):
    sources = {**values, **{key: os.environ[key] for key in ENV_KEYS if os.environ.get(key)}}
    rpc = {
        'devnet': validate_url(sources.get('SOLANA_DEVNET_RPC_URL') or sources.get('SOLANA_RPC_URL'), 'SOLANA_RPC_URL'),
        'mainnet-beta': validate_url(sources.get('SOLANA_MAINNET_RPC_URL'), 'SOLANA_MAINNET_RPC_URL'),
        'testnet': validate_url(sources.get('SOLANA_TESTNET_RPC_URL'), 'SOLANA_TESTNET_RPC_URL'),
    }
    program_accounts = {
        'devnet': validate_url(sources.get('SOLANA_PROGRAM_ACCOUNTS_RPC_URL'), 'SOLANA_PROGRAM_ACCOUNTS_RPC_URL'),
        'mainnet-beta': validate_url(sources.get('SOLANA_PROGRAM_ACCOUNTS_MAINNET_RPC_URL'), 'SOLANA_PROGRAM_ACCOUNTS_MAINNET_RPC_URL'),
        'testnet': validate_url(sources.get('SOLANA_PROGRAM_ACCOUNTS_TESTNET_RPC_URL'), 'SOLANA_PROGRAM_ACCOUNTS_TESTNET_RPC_URL'),
    }
    rpc = {key: value for key, value in rpc.items() if value}
    program_accounts = {key: value for key, value in program_accounts.items() if value}
    return (
        '// Generated by scripts/build-solana-rpc-config.py; do not commit this file.\n'
        f'globalThis.SOLANA_RPC_URLS = Object.freeze({json.dumps(rpc, separators=(",", ":"))});\n'
        'globalThis.SOLANA_PROGRAM_ACCOUNTS_RPC_URLS = '
        f'Object.freeze({json.dumps(program_accounts, separators=(",", ":"))});\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--env', required=True, type=Path, help='Local .env containing RPC endpoints')
    parser.add_argument('--out', required=True, type=Path, help='Ignored browser rpc-config.js to generate')
    args = parser.parse_args()
    try:
        content = build_config(read_env_file(args.env))
    except ValueError as error:
        parser.error(str(error))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(content)
    print('Solana browser RPC configuration generated (endpoint values omitted).')


if __name__ == '__main__':
    main()
